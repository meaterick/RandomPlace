function polygons(g){return (g.type==='Polygon'?[g.arcs]:g.arcs).map(p=>p.map(ring));}
function inRing([x,y],r){let inside=false;for(let i=0,j=r.length-1;i<r.length;j=i++){const [a,b]=r[i],[c,d]=r[j];if((b>y)!==(d>y)&&x<(c-a)*(y-b)/(d-b)+a)inside=!inside;}return inside;}
const inPolygon=(pt,rings)=>inRing(pt,rings[0])&&!rings.slice(1).some(r=>inRing(pt,r));
function km([x,y],[a,b],[c,d]){const k=Math.cos(y*Math.PI/180),dx=(c-a)*k,dy=d-b,px=(x-a)*k,py=y-b,t=dx*dx+dy*dy?Math.max(0,Math.min(1,(px*dx+py*dy)/(dx*dx+dy*dy))):0;return Math.hypot(px-t*dx,py-t*dy)*111;}
const municipalityName=name=>name.match(/^(.+?시).+구$/)?.[1]||name;

const units=Object.values(topology.objects)[0].geometries.map(g=>({province:g.properties.code.slice(0,2),name:municipalityName(g.properties.name),polygons:polygons(g)}));
function locate(pt){
  const inside=units.find(u=>u.polygons.some(p=>inPolygon(pt,p)));
  if(inside)return inside;
  let best=null,distance=Infinity;
  for(const u of units)for(const p of u.polygons)for(const r of p)for(let i=0,j=r.length-1;i<r.length;j=i++){const d=km(pt,r[j],r[i]);if(d<distance){distance=d;best=u;}}
  return distance<=4?best:null;
}

